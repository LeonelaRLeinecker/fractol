#include "fractol.h"

int	julia(t_complex z, t_complex c)
{
	int i;

	i = 0;
	while (i < MAX_ITER && get_module(z) < 4)
	{
		z = add_complex(pow_complex(z), c);
		i++;
	}
	return (i);
}

